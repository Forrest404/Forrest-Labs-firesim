/**
 * GeoJSON export of simulation results (RFC 7946: WGS84 [lon, lat], exterior rings counter-clockwise,
 * holes clockwise, rings closed). Fire perimeters are contours of the arrival-time field; ensemble
 * probability lines are contours of the burn-probability field.
 *
 * Every file carries a disclaimer because an exported file loses the app's on-screen notice: the
 * model is simplified and the output must not be used for real-world decisions.
 */

import { ENSEMBLE_TIME_BINS } from '../contract';
import type { CellRef, EnsembleResult, GridSpec, Intervention, SimResult } from '../contract';
import { contourPolygons, polygonArea, ringLength } from '../data/contours';
import type { ContourPolygon, Pt } from '../data/contours';
import { cellCenterLonLat, cellFloatToLonLat } from '../data/geo';
import { probabilityAt } from '../sim/ensemble';

export const EXPORT_DISCLAIMER =
  'Simplified model. Not for real-world decisions. Generated by a demo wildfire simulator with uncalibrated, placeholder parameters; it is not a forecast and has not been validated against real fires.';

export type Position = [number, number];
export interface GeoJsonGeometry {
  type: 'Polygon' | 'MultiPolygon' | 'Point' | 'MultiPoint';
  coordinates: unknown;
}
export interface GeoJsonFeature {
  type: 'Feature';
  geometry: GeoJsonGeometry;
  properties: Record<string, unknown>;
}
export interface GeoJsonCollection {
  type: 'FeatureCollection';
  /** Foreign members (allowed by RFC 7946). */
  disclaimer: string;
  generator: string;
  properties?: Record<string, unknown>;
  bbox?: [number, number, number, number];
  features: GeoJsonFeature[];
}

export interface ExportContext {
  grid: GridSpec;
  /** Name of the demo area and whether its data is synthetic. */
  areaName?: string;
  areaIsSynthetic?: boolean;
  /** The demo area's data sources and licences (OSM ODbL, ESA WorldCover CC BY 4.0, ...). Exported results are derived data and must keep them. */
  attribution?: string[];
}

/** Signed area of a lon/lat ring (positive = counter-clockwise). */
function lonLatArea(ring: readonly Position[]): number {
  let a = 0;
  for (let i = 0, n = ring.length; i < n; i++) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[(i + 1) % n];
    a += x1 * y2 - x2 * y1;
  }
  return a / 2;
}

/** Coordinates are rounded to 6 decimals (about 0.1 m): ample for 30 m cells and 3-4x smaller files. */
const round6 = (v: number): number => Math.round(v * 1e6) / 1e6;

function toRing(grid: GridSpec, ring: readonly Pt[], wantCounterClockwise: boolean): Position[] {
  const pts: Position[] = ring.map(([x, y]) => {
    const { lon, lat } = cellFloatToLonLat(grid, x, y);
    return [round6(lon), round6(lat)];
  });
  if ((lonLatArea(pts) > 0) !== wantCounterClockwise) pts.reverse();
  pts.push([pts[0][0], pts[0][1]]); // close
  return pts;
}

function polygonCoordinates(grid: GridSpec, p: ContourPolygon): Position[][] {
  return [toRing(grid, p.outer, true), ...p.holes.map((h) => toRing(grid, h, false))];
}

function geometryOf(grid: GridSpec, polys: ContourPolygon[]): GeoJsonGeometry | null {
  if (polys.length === 0) return null;
  if (polys.length === 1) return { type: 'Polygon', coordinates: polygonCoordinates(grid, polys[0]) };
  return { type: 'MultiPolygon', coordinates: polys.map((p) => polygonCoordinates(grid, p)) };
}

function sizeProps(grid: GridSpec, polys: ContourPolygon[]): { areaHa: number; perimeterKm: number } {
  const cellHa = (grid.cellSizeM * grid.cellSizeM) / 10_000;
  let cells = 0;
  let len = 0;
  for (const p of polys) {
    cells += polygonArea(p);
    len += ringLength(p.outer) + p.holes.reduce((s, h) => s + ringLength(h), 0);
  }
  return { areaHa: cells * cellHa, perimeterKm: (len * grid.cellSizeM) / 1000 };
}

function bboxOf(features: GeoJsonFeature[]): [number, number, number, number] | undefined {
  let w = Infinity, s = Infinity, e = -Infinity, n = -Infinity;
  const visit = (c: unknown): void => {
    if (Array.isArray(c) && typeof c[0] === 'number') {
      w = Math.min(w, c[0]); e = Math.max(e, c[0]); s = Math.min(s, c[1] as number); n = Math.max(n, c[1] as number);
    } else if (Array.isArray(c)) c.forEach(visit);
  };
  for (const f of features) visit(f.geometry.coordinates);
  return Number.isFinite(w) ? [w, s, e, n] : undefined;
}

function header(ctx: ExportContext, kind: string, extra: Record<string, unknown>): Pick<GeoJsonCollection, 'type' | 'disclaimer' | 'generator' | 'properties'> {
  return {
    type: 'FeatureCollection',
    disclaimer: EXPORT_DISCLAIMER,
    generator: 'firesim (simplified demo model)',
    properties: { kind, area: ctx.areaName ?? null, areaIsSynthetic: ctx.areaIsSynthetic ?? null, attribution: ctx.attribution ?? [], cellSizeM: ctx.grid.cellSizeM, ...extra },
  };
}

export interface PerimeterOptions {
  /** Times (seconds) at which to draw perimeters. Default: every hour up to the duration, plus the end. */
  timesS?: number[];
  ignition?: CellRef[];
  interventions?: Intervention[];
  durationSeconds: number;
}

/** Evenly spaced hourly times up to the duration (at most 48), always ending at the duration. */
export function defaultPerimeterTimes(durationSeconds: number): number[] {
  const step = Math.max(3600, Math.ceil(durationSeconds / 48 / 3600) * 3600);
  const times: number[] = [];
  for (let t = step; t < durationSeconds; t += step) times.push(t);
  times.push(durationSeconds);
  return times;
}

/** Fire perimeters (isochrones) of one run, plus the ignition point and the firefighting actions. */
export function perimetersToGeoJSON(ctx: ExportContext, result: SimResult, opts: PerimeterOptions): GeoJsonCollection {
  const { grid } = ctx;
  const features: GeoJsonFeature[] = [];
  const times = opts.timesS ?? defaultPerimeterTimes(opts.durationSeconds);
  for (const t of times) {
    const polys = contourPolygons(result.arrivalTime, grid.width, grid.height, t, 'below');
    const geometry = geometryOf(grid, polys);
    if (!geometry) continue;
    features.push({
      type: 'Feature',
      geometry,
      properties: { kind: 'perimeter', tSeconds: t, tHours: t / 3600, ...sizeProps(grid, polys), polygons: polys.length },
    });
  }
  for (const ig of opts.ignition ?? []) {
    const { lon, lat } = cellCenterLonLat(grid, ig.row, ig.col);
    features.push({ type: 'Feature', geometry: { type: 'Point', coordinates: [round6(lon), round6(lat)] }, properties: { kind: 'ignition', row: ig.row, col: ig.col } });
  }
  for (const iv of opts.interventions ?? []) {
    const coords: Position[] = iv.cells.map((c) => {
      const { lon, lat } = cellCenterLonLat(grid, Math.floor(c / grid.width), c % grid.width);
      return [round6(lon), round6(lat)];
    });
    if (coords.length === 0) continue;
    features.push({
      type: 'Feature',
      geometry: { type: 'MultiPoint', coordinates: coords },
      properties: { kind: iv.type, id: iv.id, tSeconds: iv.tSeconds, cells: coords.length },
    });
  }
  const out: GeoJsonCollection = {
    ...header(ctx, 'fire-perimeters', { burnedAreaHa: result.stats.burnedAreaHa, durationSeconds: opts.durationSeconds, spotFires: result.stats.spotFires }),
    features,
  };
  const bbox = bboxOf(features);
  if (bbox) out.bbox = bbox;
  return out;
}

export interface ProbabilityOptions {
  /** Probability levels (0-1). Default 10 %, 50 %, 90 %. */
  levels?: number[];
  /** Time (seconds) at which "burned by then" is evaluated. Default: the end of the run. */
  tSeconds?: number;
}

/** Lines of equal burn probability from an ensemble: "at least this likely to have burned by t". */
export function probabilityToGeoJSON(ctx: ExportContext, ens: EnsembleResult, opts: ProbabilityOptions = {}): GeoJsonCollection {
  const { grid } = ctx;
  const t = opts.tSeconds ?? ens.durationSeconds;
  const p = t >= ens.durationSeconds ? ens.burnProbability : probabilityAt(ens, t);
  const features: GeoJsonFeature[] = [];
  for (const level of opts.levels ?? [0.1, 0.5, 0.9]) {
    const polys = contourPolygons(p, grid.width, grid.height, level - 1e-9, 'above');
    const geometry = geometryOf(grid, polys);
    if (!geometry) continue;
    features.push({ type: 'Feature', geometry, properties: { kind: 'probability', probability: level, tSeconds: t, ...sizeProps(grid, polys), polygons: polys.length } });
  }
  const out: GeoJsonCollection = {
    ...header(ctx, 'burn-probability', { runs: ens.runs, meanAreaHa: ens.area.meanHa, p10AreaHa: ens.area.p10Ha, p90AreaHa: ens.area.p90Ha, timeSlices: ENSEMBLE_TIME_BINS }),
    features,
  };
  const bbox = bboxOf(features);
  if (bbox) out.bbox = bbox;
  return out;
}
