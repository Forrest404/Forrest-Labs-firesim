/**
 * Synthetic demo areas: rolling hills from seeded noise, a river, roads, patches of forest,
 * scrub, grass and farmland. Clearly labelled synthetic (meta.synthetic = true) everywhere.
 * Used because Overpass was unreachable when v0 was built; see DECISIONS.md D8.
 */

import { FuelClass } from '../contract';
import type { CellRef } from '../contract';
import type { DemoArea } from './bundle';
import { makeGridSpec } from './geo';
import { valueNoise } from './noise';
import { discCells, lineCells } from './raster';
import type { Pt } from './raster';

export type SyntheticStyle = 'valley' | 'ridge';

export interface SyntheticOptions {
  name: string;
  label: string;
  centerLon: number;
  centerLat: number;
  seed: number;
  style: SyntheticStyle;
  width?: number;
  height?: number;
}

export function makeSyntheticArea(o: SyntheticOptions): DemoArea {
  const grid = makeGridSpec({ centerLon: o.centerLon, centerLat: o.centerLat, width: o.width, height: o.height });
  const { width: W, height: H } = grid;
  const n = W * H;
  const terrainNoise = valueNoise(o.seed, W, H, 45, 3);
  const vegNoise = valueNoise(o.seed + 7, W, H, 22, 3);
  const farmNoise = valueNoise(o.seed + 13, W, H, 34, 2);

  const riverX = (r: number): number =>
    o.style === 'valley' ? W / 2 + 18 * Math.sin(r / 11) + 7 * Math.sin(r / 4.3) : W * 0.86 + 5 * Math.sin(r / 9);

  const elevation = new Float32Array(n);
  for (let r = 0; r < H; r++) {
    for (let c = 0; c < W; c++) {
      const i = r * W + c;
      const noise = (terrainNoise[i] - 0.5) * 140;
      if (o.style === 'valley') {
        const d = Math.abs(c - riverX(r));
        elevation[i] = 180 + d * 4.2 + noise * 0.8;
      } else {
        const axis = W * 0.42 + (r - H / 2) * 0.25;
        const d = Math.abs(c - axis);
        const toRiver = Math.max(0, c - riverX(r)) * 3;
        elevation[i] = 240 + 420 * Math.exp(-(d / 42) * (d / 42)) + noise - toRiver;
      }
    }
  }

  const fuel = new Uint8Array(n).fill(FuelClass.GRASS);
  const sortedElev = Float32Array.from(elevation).sort();
  const medianElev = sortedElev[n >> 1];
  for (let r = 0; r < H; r++) {
    for (let c = 0; c < W; c++) {
      const i = r * W + c;
      const v = vegNoise[i];
      const nearRiver = Math.abs(c - riverX(r)) < 26;
      if (v > 0.52) fuel[i] = elevation[i] > medianElev ? FuelClass.FOREST_CONIFER : FuelClass.FOREST_DECIDUOUS;
      else if (v > 0.44) fuel[i] = FuelClass.SHRUB;
      else if (nearRiver && farmNoise[i] > 0.6) fuel[i] = FuelClass.FARMLAND;
    }
  }

  // River (2 cells wide) and a small lake.
  for (let r = 0; r < H; r++) {
    const c0 = Math.round(riverX(r));
    for (const c of [c0, c0 + 1]) if (c >= 0 && c < W) fuel[r * W + c] = FuelClass.NONE;
  }
  const lakeR = o.style === 'valley' ? H * 0.72 : H * 0.2;
  for (const i of discCells(W, H, riverX(lakeR) + 3, lakeR, 5)) fuel[i] = FuelClass.NONE;

  // Roads: one east-west, and for the ridge style also one north-south. 4-connected lines.
  const ew: Pt[] = [];
  for (let c = 0; c <= W; c += 4) ew.push([c, H * 0.58 + 5 * Math.sin(c / 17)]);
  for (const i of lineCells(W, H, ew, 1)) fuel[i] = FuelClass.NONE;
  if (o.style === 'ridge') {
    const ns: Pt[] = [];
    for (let r = 0; r <= H; r += 4) ns.push([W * 0.3 + 4 * Math.sin(r / 15), r]);
    for (const i of lineCells(W, H, ns, 1)) fuel[i] = FuelClass.NONE;
  }

  // A small village: a few non-burnable blocks near the road and river.
  const vr = Math.round(H * 0.58);
  const vc = Math.round(riverX(vr)) - 12;
  for (let k = 0; k < 6; k++) {
    const rr = vr + 2 + (k % 3) * 3;
    const cc = vc + Math.floor(k / 3) * 4;
    for (let dr = 0; dr < 2; dr++) for (let dc = 0; dc < 2; dc++) {
      const r = rr + dr;
      const c = cc + dc;
      if (r >= 0 && r < H && c >= 0 && c < W) fuel[r * W + c] = FuelClass.NONE;
    }
  }

  // Valley: west of the river so the wind pushes the fire toward it. Ridge: east of the N-S road
  // (which sits at ~0.3 W) so the fire has room to run up the ridge.
  const ignCol = o.style === 'valley' ? Math.round(W * 0.2) : Math.round(W * 0.45);
  const suggestedIgnition = findBurnableNear(fuel, W, H, Math.round(H * 0.5), ignCol);
  return {
    meta: {
      name: o.name,
      label: `${o.label} (synthetic)`,
      synthetic: true,
      description: `Generated terrain and land cover (${o.style}). Not a real place. Coordinates are only a frame of reference.`,
      source: 'scripts/make-synthetic.ts',
      attribution: ['Synthetic data generated by this project'],
      license: 'Same as the repository',
      createdAt: new Date(0).toISOString(),
      suggestedIgnition,
      defaultWindFromDeg: 250,
    },
    grid,
    fuel,
    elevation,
  };
}

function findBurnableNear(fuel: Uint8Array, W: number, H: number, row: number, col: number): CellRef {
  for (let radius = 0; radius < Math.max(W, H); radius++) {
    for (let dr = -radius; dr <= radius; dr++) {
      for (let dc = -radius; dc <= radius; dc++) {
        const r = row + dr;
        const c = col + dc;
        if (r < 0 || c < 0 || r >= H || c >= W) continue;
        const f = fuel[r * W + c];
        if (f === FuelClass.FOREST_CONIFER || f === FuelClass.FOREST_DECIDUOUS || f === FuelClass.SHRUB) return { row: r, col: c };
      }
    }
  }
  return { row, col };
}
